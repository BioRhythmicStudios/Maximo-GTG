#!/usr/bin/env bash
# Rebuilds smaa_spv.h: Granite's SMAA shaders (assets/shaders/post/smaa_*.{vert,frag} + SMAA.hlsl, Jorge Jimenez et
# al., MIT) compiled to SPIR-V for the MAXIMO_SMAA pass in gpu_shadow.cpp. Quality preset ULTRA (3), no subpixel
# (temporal) mode, luma edge detection, gamma-space UNORM input.
#   build_smaa_spv.sh <glslangValidator> <Granite dir>
set -eu
G=$1; GR=$2
here="$(cd "$(dirname "$0")" && pwd)"
post="$GR/assets/shaders/post"
tmp="$(mktemp -d)"
out="$here/smaa_spv.h"
printf '// Generated by build_smaa_spv.sh from Granite assets/shaders/post (SMAA: MIT, Jorge Jimenez et al.).\n#pragma once\n#include <cstdint>\n' > "$out"
for s in edge_detection blend_weight neighbor_blend; do
    for stage in vert frag; do
        sed 's/^#version 450\r\?$/#version 450\n#extension GL_GOOGLE_include_directive : require/' "$post/smaa_$s.$stage" > "$tmp/smaa_$s.$stage"
        "$G" -V --target-env vulkan1.1 -S $stage -DSMAA_QUALITY=3 -DSMAA_SUBPIXEL_MODE=0 -DSMAA_TARGET_SRGB=0 \
            -I"$post" -I"$GR/assets/shaders/inc" -I"$GR/assets/shaders" \
            --vn maximo_smaa_${s}_$stage -o "$tmp/$s.$stage.h" "$tmp/smaa_$s.$stage"
        grep -v "pragma once" "$tmp/$s.$stage.h" | grep -v "^\s*//" >> "$out"
    done
done
rm -rf "$tmp"
echo "wrote $out"
